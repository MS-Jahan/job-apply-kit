class InstalledResumeSkillTests(unittest.TestCase):
    """Cross-skill token references resolve from the repo checkout (skills run in place)."""

    def test_char_count_reachable_via_token_resolution(self):
        text = (REPO / "skills" / "make-resume" / "SKILL.md").read_text()
        m = re.search(r"python3 (\S*helpers/char_count\.py)", text)
        self.assertIsNotNone(m)
        # OPERATIONS.md token rule: {{RESUME_KIT_DIR}} = <repo>/skills/resume-kit
        resolved = m.group(1).replace("{{RESUME_KIT_DIR}}", str(REPO / "skills" / "resume-kit"))
        helper = Path(resolved)
        self.assertTrue(helper.is_file(), helper)
        r2 = subprocess.run([sys.executable, str(helper), "--help"], capture_output=True, text=True)
        self.assertIn(r2.returncode, (0, 1, 2))  # just must run, not crash on import/path errors


class CreateTemplateSkeletonTests(unittest.TestCase):
    ASSETS = REPO / "skills" / "create-template" / "assets"

    def test_no_em_dash_as_a_token_separator(self):
        # A line like '\textbf{[[X]]} — [[Y]]' puts a real em-dash between two placeholders, so any
        # document generated by filling the tokens would ship with a banned em-dash (OPERATIONS
        # #format). Comments (%) are exempt since they never render.
        bad = re.compile(r"\]\]\}?\s*—|—\s*\[\[")
        for f in self.ASSETS.glob("*.tex"):
            for line in f.read_text(encoding="utf-8").splitlines():
                code = line.split("%", 1)[0]
                self.assertIsNone(bad.search(code), f"{f.name}: {line!r}")

    def test_skeletons_exist_for_all_three_document_types(self):
        names = {p.name for p in self.ASSETS.glob("*.tex")}
        self.assertEqual(names, {"CV_SKELETON.tex", "RESUME_SKELETON.tex", "CL_SKELETON.tex"})


class ResumeKitLineBreakHazardTests(unittest.TestCase):
    TEMPLATES = REPO / "skills" / "resume-kit" / "templates"

    def test_no_linebreak_before_bracket(self):
        # `\\` followed by `[` is parsed as an optional length argument, so a
        # line break before a bracketed placeholder ('...End]}\\\n[FIXED: ...'
        # or 'Sincerely,\\\n[Your Name]') fails with 'Missing number, treated
        # as zero'. The fix is `\\{}` (empty group blocks the parse, renders
        # identically). Legitimate lengths like `\\[1pt]` are allowed.
        # Comments (%) are exempt since they never render.
        inline_bad = re.compile(r"\\\\\[(?![\d.\-+\\])")
        for f in self.TEMPLATES.glob("*.tex"):
            lines = f.read_text(encoding="utf-8").splitlines()
            for i, line in enumerate(lines):
                code = line.split("%", 1)[0]
                self.assertIsNone(
                    inline_bad.search(code), f"{f.name}:{i + 1}: {line!r}")
                if re.search(r"\\\\\s*$", code) and i + 1 < len(lines):
                    nxt = lines[i + 1].split("%", 1)[0]
                    self.assertFalse(
                        re.match(r"\s*\[", nxt),
                        f"{f.name}:{i + 1} ends with \\\\ and next line "
                        f"starts with '[': {lines[i + 1]!r}")



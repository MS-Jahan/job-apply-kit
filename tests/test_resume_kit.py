class ResumeKitContentTests(unittest.TestCase):
    def test_no_claude_md_or_hermes_references(self):
        for f in RK.rglob("*.md"):
            text = f.read_text(encoding="utf-8", errors="replace")
            self.assertNotIn("CLAUDE.md", text, f.relative_to(REPO))
            self.assertNotIn("hermes", text.lower(), f.relative_to(REPO))

    def test_generated_kb_files_not_shipped(self):
        # skills_taxonomy / pub_metadata / achievement_reframing_guide / significance_* are built by
        # setup-build-kb from cv_source, not shipped as static reference data.
        names = {p.name for p in (RK / "support").glob("*.md")}
        for bad in ("skills_taxonomy.md", "pub_metadata.md", "achievement_reframing_guide.md"):
            self.assertNotIn(bad, names)
        self.assertFalse(list((RK / "support").glob("significance_*.md")))

    def test_workflow_b_context_note_present(self):
        text = (RK / "reference" / "resume_reference.md").read_text()
        self.assertIn("Workflow B", text)
        self.assertIn("create-template", text)

    def test_tectonic_is_default_compiler(self):
        text = (RK / "reference" / "resume_reference.md").read_text()
        self.assertIn("tectonic", text)

    def test_shared_ops_points_at_workspace_sessions_and_core_sources(self):
        text = (RK / "reference" / "shared_ops.md").read_text()
        self.assertIn("<workspace>/SESSIONS.md", text)
        self.assertIn("OPERATIONS.md#sources", text)
        self.assertNotIn("https://cv.", text)  # no hard-coded live-source domain

    def test_fictional_examples_are_not_real(self):
        # the shipped example session/resume fixtures must be the fictional Whitfield set, not real data
        text = (RK / "examples" / "example_session_file.md").read_text()
        self.assertIn("Whitfield", text)


